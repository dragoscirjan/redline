import { createHash } from 'node:crypto';
import { readFile } from 'node:fs/promises';
import { describe, expect, it } from 'vitest';

const examples = [
  { id: 'local-review', type: 'architecture' },
  { id: 'rpc-lifecycle', type: 'lifecycle' },
] as const;
const read = (path: string) => readFile(new URL('../' + path, import.meta.url), 'utf8');

describe('Archify documentation artifacts', () => {
  it('keeps previews and interactive links in the existing guides', async () => {
    const protocol = await read('docs/stdio-protocol.md');
    const architecture = await read('docs/portable-architecture.md');
    for (const { id } of examples) {
      expect(protocol).toContain('/diagrams/' + id + '.svg');
      expect(protocol).toContain('/diagrams/' + id + '.html');
    }
    expect(architecture).toContain('/diagrams/local-review.svg');
    expect(architecture).toContain('/diagrams/local-review.html');
    expect(protocol).not.toContain('<iframe');
    expect(architecture).not.toContain('<iframe');
  });

  it.each(examples)('pins the source and generated bytes for $id', async ({ id, type }) => {
    const manifest = JSON.parse(await read('docs/diagrams/manifest.json'));
    expect(manifest.generator).toMatchObject({ name: 'Archify', version: '3.2.0', revision: '208acba8d412335185b2056fedf54b3405df43fb' });
    const entry = manifest.diagrams.find((item: { id: string }) => item.id === id);
    expect(entry.type).toBe(type);
    expect(entry.checks).toEqual({ quality: 'showcase', validate: 'pass', deliver: 'pass', artifact: 'pass', browser: 'pass' });
    for (const kind of ['specification', 'html', 'svg']) {
      const bytes = await readFile(new URL('../' + String(entry[kind].path), import.meta.url));
      expect(bytes.length).toBe(entry[kind].bytes);
      expect(createHash('sha256').update(bytes).digest('hex')).toBe(entry[kind].sha256);
    }
    const spec = JSON.parse(await read('docs/diagrams/' + id + '.' + type + '.json'));
    expect(spec.meta.repository.revision).toBe(manifest.sourceRevision);
    expect(spec.meta.output).toBe(entry.html.path);
    for (const node of spec.components ?? spec.states) {
      expect(node.sources.length).toBeGreaterThan(0);
      for (const source of node.sources) {
        const text = await read(String(source.path));
        expect(source.line).toBeGreaterThan(0);
        expect(source.end_line).toBeLessThanOrEqual(text.split('\n').length);
      }
    }
    const attributes = await read('.gitattributes');
    expect(attributes).toContain('docs/diagrams/*.json text eol=lf');
    expect(attributes).toContain('docs/public/diagrams/* text eol=lf');
  });

  it.each(examples)('keeps $id self-contained and its preview script-free', async ({ id }) => {
    const html = await read('docs/public/diagrams/' + id + '.html');
    const svg = await read('docs/public/diagrams/' + id + '.svg');
    for (const text of [html, svg]) {
      expect(text).not.toMatch(/\/home\/dragosc|\/tmp\/redline/u);
      expect(text).not.toMatch(/<script\b[^>]*\bsrc\s*=/iu);
      expect(text).toContain('SIL OPEN FONT LICENSE');
    }
    expect(svg).not.toMatch(/<script\b|<foreignObject\b/iu);
    expect(svg).not.toMatch(/(?:href|src)=["']https?:/iu);
  });

  it('uses the six public run states without inventing a cancelling state', async () => {
    const spec = JSON.parse(await read('docs/diagrams/rpc-lifecycle.lifecycle.json'));
    expect(spec.states.map((state: { id: string }) => state.id).sort()).toEqual([
      'cancelled', 'completed', 'failed', 'incomplete', 'running', 'timed-out',
    ]);
    expect(spec.transitions.every((transition: { from: string }) => transition.from === 'running')).toBe(true);
  });
});
